import assert from 'node:assert/strict';
import test from 'node:test';

import {
  buildSavedProposalAnswer,
  classifyAssistantQuestion,
  hasVerifiedProposalClaims,
} from '../src/proposalAssistant.js';

const motorolaId = 'motorola-test-company';
const xiaomiId = 'xiaomi-test-company';

test('proposal recommendation warning requires a verified source-backed claim', () => {
  assert.equal(hasVerifiedProposalClaims({ claims: [] }), false);
  assert.equal(hasVerifiedProposalClaims({
    claims: [{ verification_status: 'unverified', source_ids: [] }],
  }), false);
  assert.equal(hasVerifiedProposalClaims({
    claims: [{ verification_status: 'verified', source_ids: [] }],
  }), false);
  assert.equal(hasVerifiedProposalClaims({
    claims: [{ verification_status: 'verified', source_ids: ['source-1'] }],
  }), true);
});

// Labelled fixture based on the shape of saved proposal records. It is not a
// company fact or a historical product event.
const motorolaProposal = {
  id: 'synthetic-moto-shield-proposal',
  company_id: motorolaId,
  title: '[SYNTHETIC] Moto Shield AI proposal',
  description: [
    'Objective: AI-based scam detection and smartphone privacy protection.',
    '',
    'Proposed Features:',
    '- Detect suspicious calls and text messages.',
    '',
    'Proposed Experiment:',
    'Run a controlled pilot with selected Motorola users and compare against existing device security controls.',
    '',
    'Success Metrics:',
    'Detection precision, recall, false-positive rate, and user confidence.',
  ].join('\n'),
  status: 'submitted',
  workflow_status: 'completed',
  analyses: [{
    id: 'synthetic-moto-shield-analysis',
    status: 'completed',
    accessible: true,
    recommendation: 'PILOT – Run a controlled pilot with selected users.',
    risks: ['Technical feasibility', 'Training data quality', 'Privacy and user adoption'],
    limitations: ['Recommendations, risks and interpretations are generated by Qwen.'],
  }],
};

const xiaomiProposal = {
  ...motorolaProposal,
  id: 'synthetic-xiaomi-proposal',
  company_id: xiaomiId,
  title: '[SYNTHETIC] Xiaomi-only proposal',
};

test('proposal summary returns the actual saved description as user-submitted content', () => {
  const answer = buildSavedProposalAnswer(
    'Summarize my Moto Shield AI proposal',
    [motorolaProposal],
    motorolaId,
  );

  assert.equal(answer.proposals.length, 1);
  assert.match(answer.proposals[0].description, /AI-based scam detection and smartphone privacy protection/);
  assert.equal(answer.proposals[0].blocks[0].label, 'Proposal objective · user-submitted content');
  assert.equal(answer.historicalProof, false);
});

test('proposal experiment answer returns the experiment saved in the description', () => {
  const answer = buildSavedProposalAnswer(
    'What experiments were proposed?',
    [motorolaProposal],
    motorolaId,
  );

  assert.equal(answer.proposals[0].blocks[0].label, 'Experiment described in the user-submitted proposal');
  assert.match(answer.proposals[0].blocks[0].text, /controlled pilot with selected Motorola users/);
});

test('proposal recommendation answer returns the saved analysis recommendation and attribution', () => {
  const answer = buildSavedProposalAnswer(
    'What recommendation did NEXUS generate?',
    [motorolaProposal],
    motorolaId,
  );

  assert.equal(answer.proposals[0].blocks[0].text, motorolaProposal.analyses[0].recommendation);
  assert.match(answer.proposals[0].blocks[0].label, /Qwen/);
});

test('proposal risk answer returns risks stored in the saved analysis', () => {
  const answer = buildSavedProposalAnswer(
    'What risks did the analysis identify?',
    [motorolaProposal],
    motorolaId,
  );

  assert.equal(answer.proposals[0].blocks[0].label, 'Risks identified by the saved AI analysis');
  assert.match(answer.proposals[0].blocks[0].text, /Technical feasibility/);
  assert.match(answer.proposals[0].blocks[0].text, /Privacy and user adoption/);
});

test('a question asking whether Moto Shield AI launched is split from proposal content', () => {
  const intent = classifyAssistantQuestion(
    'Was Moto Shield AI actually launched?',
    [motorolaProposal],
    motorolaId,
  );
  const answer = buildSavedProposalAnswer(
    'Was Moto Shield AI actually launched?',
    [motorolaProposal],
    motorolaId,
    intent,
  );

  assert.equal(intent.mixed, true);
  assert.equal(intent.asksAboutHistory, true);
  assert.equal(intent.asksAboutProposals, true);
  assert.equal(answer.historicalProof, false);
  assert.match(answer.proposals[0].blocks.at(-1).label, /Saved recommendation/);
  assert.match(answer.message, /not documentary proof of a launch/);
});

test('an unrelated historical question routes to evidence-grounded RAG only', () => {
  const intent = classifyAssistantQuestion(
    'When did Motorola discontinue the Moto Razr?',
    [motorolaProposal],
    motorolaId,
  );

  assert.equal(intent.asksAboutHistory, true);
  assert.equal(intent.asksAboutProposals, false);
  assert.equal(intent.mixed, false);
});

test('a service shutdown question routes to historical evidence retrieval', () => {
  const intent = classifyAssistantQuestion(
    'When did Google Stadia shut down?',
    [],
    'stadia-test-company',
  );

  assert.equal(intent.asksAboutHistory, true);
  assert.equal(intent.asksAboutProposals, false);
  assert.equal(intent.mixed, false);
});

test('saved proposal answers are strictly scoped to the selected company', () => {
  const answer = buildSavedProposalAnswer(
    'What proposals have I submitted?',
    [xiaomiProposal],
    motorolaId,
  );

  assert.deepEqual(answer.proposals, []);
  assert.match(answer.message, /No saved proposal records were found/);
});
